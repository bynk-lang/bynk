#!/usr/bin/env node
// Build the artifacts bynk-emit embeds from the @bynk/runtime modules (ADR 0615):
//
//  - the per-module runtime: each module as `src/emitter/runtime/<module>.ts`
//    (with its `__` aliases appended) plus the `runtime_modules.rs` table of
//    sources and of exported names. A project emits the modules it reaches as
//    `__bynk_runtime/<module>.{ts,js}`;
//  - `@bynk/wire-client` (`../wire-client/index.ts`), a concatenation of the
//    boundary modules for foreign callers.
//
//   node scripts/bundle.mjs           # (re)write the artifacts
//   node scripts/bundle.mjs --check   # fail if an artifact is out of date
//
// `--check` is the drift guard: it rebuilds in memory and diffs against the
// committed files, so CI catches a stale artifact without a Node step inside
// `cargo build`.

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = join(here, "..");
const SRC = join(pkgRoot, "src");

// Module order: a topological sort of the module dependency graph, mirroring
// the re-export order in src/index.ts. `aliases` is the alias source of truth.
const MODULES = [
  "result",
  "bytes",
  "equality",
  "int",
  "errors",
  "storage",
  "boundary",
  "http",
  "queue",
  "agent",
  "auth",
  "connection",
  "messages",
  "locale",
  "aliases",
  "wasm",
];

// I4 (#1970): the second artifact, `@bynk/wire-client` — the runtime half of
// the typed TypeScript client bynkc generates for a context's foreign callers
// (`bynk-client.ts`). It is not a copy of anything: it is the same modules the
// emitted runtime is built from, the ones the call boundary needs, plus the
// package's own `surface.ts`. So a foreign caller encodes, signs and decodes
// with the code a Bynk caller runs (`design/archive/retired-tracks.md`, interop track D3, I4).
// Versioned with the wire format, not with this runtime (§11 Q7).
const CLIENT_ROOT = join(pkgRoot, "..", "wire-client");
const CLIENT_TARGET = join(CLIENT_ROOT, "index.ts");
const CLIENT_SOURCES = [
  ...["result", "bytes", "errors", "boundary"].map((name) => join(SRC, `${name}.ts`)),
  join(CLIENT_ROOT, "src", "surface.ts"),
];
const CLIENT_HEADER = [
  "// Generated by bynk-emit/runtime/scripts/bundle.mjs — do not edit by hand.",
  "// @bynk/wire-client: the runtime half of a bynkc-generated TypeScript client,",
  "// speaking the Bynk cross-context wire format, version 1. Built from the bynk",
  "// runtime's own boundary modules, so a non-Bynk caller encodes, signs and",
  "// decodes exactly as a Bynk caller does.",
].join("\n");

// Drop a module's internal cross-imports (e.g. `import { Ok } from "./result.ts";`).
// After concatenation every symbol lives in one module scope, so these imports
// are not only redundant but invalid. Only relative ("./", "../") specifiers are
// stripped; the runtime has no external dependencies, so nothing else should
// appear.
const INTERNAL_IMPORT = /^import\s[\s\S]*?\sfrom\s+["']\.\.?\/[^"']+["'];\s*$/;

function stripInternalImports(source) {
  // A multi-line import (`import {\n  a,\n} from "…";`) is joined first, so
  // the line filter below sees it whole.
  return source
    .replace(/^import\s[^;]*?\sfrom\s+["']\.\.?\/[^"']+["'];$/gms, (m) => m.replace(/\n\s*/g, " "))
    .split("\n")
    .filter((line) => !INTERNAL_IMPORT.test(line))
    .join("\n")
    .trim();
}

async function build(header, sources) {
  const bodies = [];
  for (const path of sources) {
    const raw = await readFile(path, "utf8");
    const body = stripInternalImports(raw);
    if (body.length > 0) bodies.push(body);
  }
  return `${header}\n\n${bodies.join("\n\n")}\n`;
}

const ARTIFACTS = [
  {
    target: CLIENT_TARGET,
    header: CLIENT_HEADER,
    sources: CLIENT_SOURCES,
    stale:
      "wire-client/index.ts is out of date with its sources.\n" +
      "Run `npm run bundle` in bynk-emit/runtime and commit bynk-emit/wire-client/index.ts.",
  },
];

// ADR 0615 (#2426): the per-module form of the runtime. Each module is emitted
// as its own file (`__bynk_runtime/<module>.ts`), importing its siblings by
// relative path, and carries the `__` aliases (#1653) of its own exports — the
// names emitted code imports. The table below is what bynk-emit embeds. The
// flat `runtime.ts` artifact above stays until emission switches over.
const PER_MODULE = [...MODULES.filter((m) => m !== "aliases")];
const MODULE_DIR = join(pkgRoot, "..", "src", "emitter", "runtime");
const MODULE_TABLE = join(pkgRoot, "..", "src", "emitter", "runtime_modules.rs");

// Parse src/aliases.ts into `module -> [{ name, alias, type }]`.
function parseAliases(source) {
  const byModule = new Map();
  const origin = new Map(); // imported name -> module
  for (const m of source.matchAll(/^import\s*\{([^}]*)\}\s*from\s*"\.\/([a-z]+)\.ts";$/gm)) {
    for (const raw of m[1].split(",")) {
      const item = raw.trim();
      if (item) origin.set(item.replace(/^type\s+/, ""), { module: m[2], type: item.startsWith("type ") });
    }
  }
  for (const m of source.matchAll(/^export\s+(type\s+)?\{([^}]*)\};$/gm)) {
    for (const raw of m[2].split(",")) {
      const item = raw.trim();
      if (!item) continue;
      const [name, alias] = item.split(/\s+as\s+/);
      const from = origin.get(name);
      if (!from) throw new Error(`aliases.ts exports ${name}, which it does not import`);
      if (!byModule.has(from.module)) byModule.set(from.module, []);
      byModule.get(from.module).push({ name, alias, type: from.type });
    }
  }
  return byModule;
}

function aliasBlock(entries) {
  if (!entries || entries.length === 0) return "";
  const fmt = (list) => list.map((e) => `${e.name} as ${e.alias}`).join(", ");
  const values = entries.filter((e) => !e.type);
  const types = entries.filter((e) => e.type);
  const lines = ["", "// #1653: the `__` aliases emitted code imports."];
  if (values.length) lines.push(`export { ${fmt(values)} };`);
  if (types.length) lines.push(`export type { ${fmt(types)} };`);
  return lines.join("\n");
}

async function buildPerModule() {
  const aliases = parseAliases(await readFile(join(SRC, "aliases.ts"), "utf8"));
  const files = new Map();
  for (const name of PER_MODULE) {
    const raw = await readFile(join(SRC, `${name}.ts`), "utf8");
    files.set(`${name}.ts`, `${raw.trimEnd()}\n${aliasBlock(aliases.get(name))}\n`);
  }
  // name -> defining module, for every exported name (declarations and the
  // alias lists above). The emitter splits an import of runtime names by it.
  const exported = new Map();
  for (const [file, content] of files) {
    const module = file.replace(/\.ts$/, "");
    const names = [];
    for (const m of content.matchAll(/^export\s+(?:declare\s+)?(?:abstract\s+)?(?:async\s+)?(?:const|let|function\*?|class|interface|type|enum)\s+([A-Za-z_$][\w$]*)/gm)) names.push(m[1]);
    for (const m of content.matchAll(/^export\s+(?:type\s+)?\{([^}]*)\};$/gm)) {
      for (const raw of m[1].split(",")) {
        const item = raw.trim();
        if (item) names.push(item.split(/\s+as\s+/).pop());
      }
    }
    for (const n of names) {
      if (exported.has(n) && exported.get(n) !== module) {
        throw new Error(`runtime name ${n} is exported by both ${exported.get(n)} and ${module}`);
      }
      exported.set(n, module);
    }
  }
  const exportRows = [...exported].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)).map(([n, m]) => `    ("${n}", "${m}"),`);
  const rows = PER_MODULE.map((n) => `    ("${n}", include_str!("runtime/${n}.ts")),`);
  const table = [
    "// Generated by bynk-emit/runtime/scripts/bundle.mjs — do not edit by hand.",
    "// ADR 0615: the runtime as (module name, source) pairs, one per @bynk/runtime module.",
    "pub(crate) const RUNTIME_MODULES: &[(&str, &str)] = &[",
    ...rows,
    "];",
    "",
    "/// Every name a runtime module exports, with the module that defines it.",
    "pub(crate) const RUNTIME_EXPORTS: &[(&str, &str)] = &[",
    ...exportRows,
    "];",
    "",
  ].join("\n");
  return { files, table };
}

const check = process.argv.includes("--check");
let stale = false;
{
  const { files, table } = await buildPerModule();
  const expected = new Map([...files].map(([n, c]) => [join(MODULE_DIR, n), c]));
  expected.set(MODULE_TABLE, table);
  if (check) {
    let drift = false;
    for (const [path, want] of expected) {
      let have = null;
      try {
        have = await readFile(path, "utf8");
      } catch {
        /* missing counts as drift */
      }
      if (have !== want) drift = true;
    }
    if (drift) {
      console.error(
        "the per-module runtime (src/emitter/runtime/, runtime_modules.rs) is out of date.\n" +
          "Run `npm run bundle` in bynk-emit/runtime and commit it.",
      );
      stale = true;
    } else {
      console.log("per-module runtime is up to date.");
    }
  } else {
    await mkdir(MODULE_DIR, { recursive: true });
    for (const [path, content] of expected) await writeFile(path, content, "utf8");
    console.log(`Wrote ${expected.size - 1} runtime modules and ${MODULE_TABLE}.`);
  }
}
for (const artifact of ARTIFACTS) {
  const bundled = await build(artifact.header, artifact.sources);
  if (check) {
    let current = null;
    try {
      current = await readFile(artifact.target, "utf8");
    } catch {
      /* missing target counts as drift */
    }
    if (current !== bundled) {
      console.error(artifact.stale);
      stale = true;
    } else {
      console.log(`${artifact.target} is up to date.`);
    }
  } else {
    await writeFile(artifact.target, bundled, "utf8");
    console.log(`Wrote ${artifact.target} (${bundled.length} bytes).`);
  }
}
if (stale) process.exit(1);

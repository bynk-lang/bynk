//! Events track, slice 0 (spine #936, ADR 0284): the fan-out Durable Object.
//!
//! One instance per *publishing* context. Cloudflare requires a DO's
//! `class_name` to resolve to an export of the Worker's `main` module, so
//! this is emitted as its own file (`events_fanout.ts`) and re-exported from
//! `index.ts` — mirroring how an agent's DO class lives in `handlers.ts` and
//! is re-exported the same way, except an event fan-out has no backing
//! `AgentDecl` to emit from, so this is hand-built rather than reusing
//! `emit_agent`. The subscriber registry (who gets `E`) is fully compile-time
//! known (`bynk_check::symbols::discover_event_subscribers`), so it is baked in as
//! a literal routing table rather than carried on the wire.
//!
//! Arc C's own first real conversion slice (#1317): builds a real
//! `bynk_ts::TsProgram` directly instead of `writeln!`-ing a `String` — the
//! first `bynk-emit` construction site whose output reaches
//! `Document::Ts` without a `TsStmt::verbatim` wrap.

use std::collections::BTreeMap;

use bynk_ts::{
    TsBinaryOp, TsBindingName, TsClassCtor, TsClassField, TsClassMethod, TsDecl, TsExpr, TsLit,
    TsParam, TsProgram, TsStmt, TsType, TsTypeMember, TsUnaryOp,
};

use crate::emitter::wrangler::{EVENTS_FANOUT_CLASS_NAME, service_binding};

/// The Worker-relative specifier `events_fanout.ts` imports the runtime
/// from — same depth as `compose.ts` (`workers/<worker>/events_fanout.ts`).
const EVENTS_FANOUT_RUNTIME_SPECIFIER: &str = "../../runtime.js";

/// `context`: the publishing context's qualified name (the header comment,
/// and I2's signing identity for every delivery). `routes`: this context's own declared event type names →
/// their subscribers, as `(subscriber_context, subscriber_service)` pairs —
/// already sorted (`discover_event_subscribers` sorts each `Vec`), so the
/// generated table (and so the fan-out order for a multi-subscriber event) is
/// deterministic build to build.
pub(crate) fn emit_events_fanout_do(
    context: &str,
    routes: &BTreeMap<String, Vec<(String, String)>>,
) -> TsProgram {
    let mut program = TsProgram::new();
    program.push(TsStmt::comment(
        "Generated by bynkc — do not edit by hand.",
        None,
    ));
    program.push(TsStmt::comment(
        format!("Events fan-out Durable Object for context `{context}` (spine #936, ADR 0284)."),
        None,
    ));
    for (type_only, names) in [
        (
            true,
            vec![
                "__DurableObjectState".to_string(),
                "__ServiceBinding".to_string(),
            ],
        ),
        (false, vec!["__deliverEvent".to_string()]),
    ] {
        for stmt in crate::emitter::runtime_files::runtime_import_stmts(
            type_only,
            &names,
            EVENTS_FANOUT_RUNTIME_SPECIFIER,
        ) {
            program.push(stmt);
        }
    }
    program.push(TsStmt::decl(
        TsDecl::Interface {
            name: "FanoutEvent".to_string(),
            type_params: Vec::new(),
            members: vec![
                TsTypeMember::prop("type", TsType::named("string")),
                TsTypeMember::prop("payload", TsType::named("unknown")),
                // Events track, slice 2 (spine #936): minted once at
                // emission (`lower.rs`'s `__events.push`), forwarded here
                // unchanged and always — whether a subscriber's own handler
                // actually declared the optional second `env:
                // EventEnvelope` parameter is decided downstream, at the
                // receiving context's entry route, not here.
                TsTypeMember::prop(
                    "envelope",
                    TsType::Object(vec![
                        TsTypeMember::prop("eventId", TsType::named("string")),
                        TsTypeMember::prop("publisherId", TsType::named("string")),
                        TsTypeMember::prop("emittedAt", TsType::named("number")),
                        TsTypeMember::prop("schemaVersion", TsType::named("number")),
                    ]),
                ),
            ],
        },
        None,
    ));
    program.push(TsStmt::decl(
        TsDecl::ConstDecl {
            name: "__eventRoutes".to_string(),
            ty: Some(TsType::named_with_args(
                "globalThis.Record",
                vec![
                    TsType::named("string"),
                    TsType::named_with_args(
                        "globalThis.Array",
                        vec![TsType::Object(vec![
                            TsTypeMember::prop("binding", TsType::named("string")),
                            TsTypeMember::prop("context", TsType::named("string")),
                            TsTypeMember::prop("service", TsType::named("string")),
                        ])],
                    ),
                ],
            )),
            init: event_routes_table(routes),
        },
        None,
    ));
    program.push(TsStmt::decl(
        TsDecl::Export(Box::new(TsDecl::Class {
            name: EVENTS_FANOUT_CLASS_NAME.to_string(),
            fields: vec![TsClassField {
                name: "env".to_string(),
                ty: TsType::named_with_args(
                    "globalThis.Record",
                    vec![TsType::named("string"), TsType::named("__ServiceBinding")],
                ),
                private: true,
            }],
            constructor: Some(events_fanout_ctor()),
            methods: vec![events_fanout_fetch(context)],
        })),
        None,
    ));
    program
}

/// `{ "<event type>": [{ binding: "...", context: "...", service: "..." },
/// ...], ... }` — I2 (#1971): `context` is the subscriber's qualified name,
/// which a delivery's signature binds it to —
/// built from `routes` the same "loop over real data, build real nodes"
/// pattern P7.9 already established for `Ty`/`TypeRef` conversion
/// (`bynk-emit/src/emitter.rs`'s `ts_ty_to_ts_type`/`ts_type_ref_to_ts_type`),
/// here for expressions instead of types. The outer key is pre-quoted
/// (`format!("{name:?}")`, matching the original `write!`-based code
/// byte-for-byte) since `TsExpr::Object`'s own key field is a raw string
/// pushed verbatim, not itself a `TsExpr` — there is no other way to get
/// quotes around an event-type name that isn't a bare identifier.
fn event_routes_table(routes: &BTreeMap<String, Vec<(String, String)>>) -> TsExpr {
    TsExpr::multiline_object(
        routes
            .iter()
            .map(|(name, subs)| {
                let entries = subs
                    .iter()
                    .map(|(sub_ctx, sub_svc)| {
                        TsExpr::object(vec![
                            (
                                "binding".to_string(),
                                TsExpr::Lit(TsLit::Str(service_binding(sub_ctx).name)),
                            ),
                            (
                                "context".to_string(),
                                TsExpr::Lit(TsLit::Str(sub_ctx.clone())),
                            ),
                            (
                                "service".to_string(),
                                TsExpr::Lit(TsLit::Str(sub_svc.clone())),
                            ),
                        ])
                    })
                    .collect();
                (format!("{name:?}"), TsExpr::array(entries))
            })
            .collect(),
    )
}

fn events_fanout_ctor() -> TsClassCtor {
    TsClassCtor {
        params: vec![
            TsParam {
                name: "_state".to_string(),
                ty: Some(TsType::named("__DurableObjectState")),
                optional: false,
            },
            TsParam {
                name: "env".to_string(),
                ty: Some(TsType::named("unknown")),
                optional: true,
            },
        ],
        body: vec![TsStmt::assign(
            TsExpr::Member {
                object: Box::new(TsExpr::Ident("this".to_string())),
                property: "env".to_string(),
            },
            TsExpr::As {
                expr: Box::new(TsExpr::Binary {
                    op: TsBinaryOp::NullishCoalescing,
                    left: Box::new(TsExpr::Ident("env".to_string())),
                    right: Box::new(TsExpr::object(vec![])),
                }),
                ty: TsType::named_with_args(
                    "globalThis.Record",
                    vec![TsType::named("string"), TsType::named("__ServiceBinding")],
                ),
            },
            None,
        )],
    }
}

fn events_fanout_fetch(context: &str) -> TsClassMethod {
    TsClassMethod {
        name: "fetch".to_string(),
        private: false,
        is_async: true,
        params: vec![TsParam {
            name: "request".to_string(),
            ty: Some(TsType::named("globalThis.Request")),
            optional: false,
        }],
        return_type: Some(TsType::named_with_args(
            "globalThis.Promise",
            vec![TsType::named("globalThis.Response")],
        )),
        doc: None,
        body: vec![
            TsStmt::const_stmt(
                TsBindingName::ObjectPattern(vec!["events".to_string()]),
                None,
                TsExpr::As {
                    // #1323: the `As` arm's own automatic Await-parenthesisation
                    // rule was removed (`workers_entry.rs`'s own real `await
                    // request.json() as JsonValue` has no parens — `as` binds
                    // looser than `await`, so none are grammatically needed,
                    // unlike the reasoning P7.8 originally gave). This file's
                    // own real historical text keeps its parens regardless
                    // (`(await request.json()) as { ... }`), now via an
                    // explicit `Paren`, not an implicit per-shape rule.
                    expr: Box::new(TsExpr::Paren(Box::new(TsExpr::Await(Box::new(
                        TsExpr::Call {
                            callee: Box::new(TsExpr::Member {
                                object: Box::new(TsExpr::Ident("request".to_string())),
                                property: "json".to_string(),
                            }),
                            args: vec![],
                        },
                    ))))),
                    ty: TsType::Object(vec![TsTypeMember::prop(
                        "events",
                        TsType::array(TsType::named("FanoutEvent")),
                    )]),
                },
                None,
            ),
            TsStmt::for_of(
                "ev",
                TsExpr::Ident("events".to_string()),
                TsStmt::block(
                    vec![
                        TsStmt::const_stmt(
                            TsBindingName::Ident("subs".to_string()),
                            None,
                            TsExpr::Index {
                                object: Box::new(TsExpr::Ident("__eventRoutes".to_string())),
                                index: Box::new(TsExpr::Member {
                                    object: Box::new(TsExpr::Ident("ev".to_string())),
                                    property: "type".to_string(),
                                }),
                            },
                            None,
                        ),
                        // `__eventRoutes` is a plain object literal — an
                        // event type named "toString"/"constructor"/etc
                        // would otherwise resolve off `Object.prototype` (a
                        // truthy, non-array value `??` never catches),
                        // throwing a `for...of` TypeError outside every
                        // per-subscriber `try`/`catch` below. `Array.isArray`
                        // closes it without changing the table's own
                        // literal-object shape.
                        TsStmt::if_stmt(
                            TsExpr::Unary {
                                op: TsUnaryOp::Not,
                                expr: Box::new(TsExpr::Call {
                                    callee: Box::new(TsExpr::Member {
                                        object: Box::new(TsExpr::Ident(
                                            "globalThis.Array".to_string(),
                                        )),
                                        property: "isArray".to_string(),
                                    }),
                                    args: vec![TsExpr::Ident("subs".to_string())],
                                }),
                            },
                            TsStmt::continue_stmt(None),
                            None,
                        ),
                        TsStmt::for_of(
                            "sub",
                            TsExpr::Ident("subs".to_string()),
                            TsStmt::block(
                                vec![
                                    TsStmt::const_stmt(
                                        TsBindingName::Ident("binding".to_string()),
                                        None,
                                        TsExpr::Index {
                                            object: Box::new(TsExpr::Member {
                                                object: Box::new(TsExpr::Ident("this".to_string())),
                                                property: "env".to_string(),
                                            }),
                                            index: Box::new(TsExpr::Member {
                                                object: Box::new(TsExpr::Ident("sub".to_string())),
                                                property: "binding".to_string(),
                                            }),
                                        },
                                        None,
                                    ),
                                    TsStmt::if_stmt(
                                        TsExpr::Unary {
                                            op: TsUnaryOp::Not,
                                            expr: Box::new(TsExpr::Ident("binding".to_string())),
                                        },
                                        TsStmt::continue_stmt(None),
                                        None,
                                    ),
                                    // ADR 0284: subscriber failure isolation
                                    // — one subscriber's rejection is logged
                                    // and does not stop delivery to the
                                    // remaining subscribers, nor does it
                                    // propagate back to the (already-
                                    // committed) publishing handler.
                                    TsStmt::try_catch(
                                        TsStmt::block(
                                            vec![TsStmt::expr_stmt(
                                                TsExpr::Await(Box::new(TsExpr::Call {
                                                    callee: Box::new(TsExpr::Ident(
                                                        "__deliverEvent".to_string(),
                                                    )),
                                                    args: vec![
                                                        TsExpr::Ident("binding".to_string()),
                                                        TsExpr::Member {
                                                            object: Box::new(TsExpr::Ident(
                                                                "sub".to_string(),
                                                            )),
                                                            property: "service".to_string(),
                                                        },
                                                        TsExpr::Member {
                                                            object: Box::new(TsExpr::Ident(
                                                                "ev".to_string(),
                                                            )),
                                                            property: "payload".to_string(),
                                                        },
                                                        TsExpr::Member {
                                                            object: Box::new(TsExpr::Ident(
                                                                "ev".to_string(),
                                                            )),
                                                            property: "envelope".to_string(),
                                                        },
                                                        // I2 (#1971): the key for
                                                        // the edge to the
                                                        // subscriber, and the
                                                        // two names the
                                                        // delivery is signed
                                                        // between.
                                                        TsExpr::Member {
                                                            object: Box::new(TsExpr::Ident(
                                                                "this".to_string(),
                                                            )),
                                                            property: "env".to_string(),
                                                        },
                                                        TsExpr::Lit(TsLit::Str(
                                                            context.to_string(),
                                                        )),
                                                        TsExpr::Member {
                                                            object: Box::new(TsExpr::Ident(
                                                                "sub".to_string(),
                                                            )),
                                                            property: "context".to_string(),
                                                        },
                                                    ],
                                                })),
                                                None,
                                            )],
                                            None,
                                        ),
                                        Some("e"),
                                        TsStmt::block(
                                            vec![TsStmt::expr_stmt(
                                                TsExpr::Call {
                                                    callee: Box::new(TsExpr::Member {
                                                        object: Box::new(TsExpr::Ident(
                                                            "globalThis.console".to_string(),
                                                        )),
                                                        property: "error".to_string(),
                                                    }),
                                                    args: vec![
                                                        TsExpr::Lit(TsLit::Str(
                                                            "EventsFanout delivery failed"
                                                                .to_string(),
                                                        )),
                                                        TsExpr::object(vec![
                                                            (
                                                                "event".to_string(),
                                                                TsExpr::Member {
                                                                    object: Box::new(
                                                                        TsExpr::Ident(
                                                                            "ev".to_string(),
                                                                        ),
                                                                    ),
                                                                    property: "type".to_string(),
                                                                },
                                                            ),
                                                            (
                                                                "service".to_string(),
                                                                TsExpr::Member {
                                                                    object: Box::new(
                                                                        TsExpr::Ident(
                                                                            "sub".to_string(),
                                                                        ),
                                                                    ),
                                                                    property: "service".to_string(),
                                                                },
                                                            ),
                                                            (
                                                                "error".to_string(),
                                                                TsExpr::Call {
                                                                    callee: Box::new(
                                                                        TsExpr::Ident(
                                                                            "String".to_string(),
                                                                        ),
                                                                    ),
                                                                    args: vec![TsExpr::Ident(
                                                                        "e".to_string(),
                                                                    )],
                                                                },
                                                            ),
                                                        ]),
                                                    ],
                                                },
                                                None,
                                            )],
                                            None,
                                        ),
                                        None,
                                    ),
                                ],
                                None,
                            ),
                            None,
                        ),
                    ],
                    None,
                ),
                None,
            ),
            TsStmt::return_stmt(
                Some(TsExpr::New {
                    callee: Box::new(TsExpr::Ident("globalThis.Response".to_string())),
                    args: vec![
                        TsExpr::Lit(TsLit::Null),
                        TsExpr::object(vec![(
                            "status".to_string(),
                            TsExpr::Lit(TsLit::Num("204".to_string())),
                        )]),
                    ],
                }),
                None,
            ),
        ],
    }
}

/// Arc C's own first slice (#1317, Decision D/"Done when"): the P7.8-era
/// `bynk-ts` test (`printer.rs`'s own
/// `prints_events_fanout_dos_own_class_byte_identical_to_the_real_emitter`)
/// proves the algebra can represent this file's *class* portion, built from
/// a hand-rebuilt tree — it does not exercise `emit_events_fanout_do`
/// itself, and never covered the header/imports/interface/table at all.
/// This is the fresh, direct test the accepted proposal requires: calls the
/// real, converted function with real-shaped data and asserts the printed
/// output is byte-identical to a real fixture's own `events_fanout.ts`, not
/// a hand-rebuilt approximation of it.
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn matches_the_real_fixtures_own_events_fanout_ts_byte_for_byte() {
        let expected = include_str!(
            "../../../bynkc/tests/fixtures/positive/966_event_field_default_cross_context/\
             expected/workers/commerce-order/events_fanout.ts"
        );
        let mut routes = BTreeMap::new();
        routes.insert(
            "PaymentConfirmed".to_string(),
            vec![(
                "commerce.notifications".to_string(),
                "OnPayment".to_string(),
            )],
        );
        let program = emit_events_fanout_do("commerce.order", &routes);
        let printed = bynk_ts::print(&program, "", "", "");
        assert_eq!(printed.text, expected);
    }

    /// Review of #1317/#1318, finding 1: a context can `ctx_uses_emit`
    /// while publishing only events nobody subscribes to
    /// (`bynk-emit/src/project.rs`'s own `own_event_routes` filters down to
    /// exactly this shape) — `routes` empty is real, reachable input, not
    /// hypothetical. Pins the exact pre-conversion `writeln!` behaviour:
    /// the `for` loop over `routes` just doesn't iterate, but the
    /// open-brace and closing `};` lines were written unconditionally
    /// either way.
    #[test]
    fn an_empty_routes_map_still_prints_the_open_and_close_brace_on_separate_lines() {
        let routes = BTreeMap::new();
        let program = emit_events_fanout_do("commerce.order", &routes);
        let printed = bynk_ts::print(&program, "", "", "");
        assert!(
            printed.text.contains(
                "const __eventRoutes: globalThis.Record<string, globalThis.Array<{ binding: string; context: string; service: string }>> = {\n};\n"
            ),
            "expected the empty-table shape, got:\n{}",
            printed.text
        );
    }
}

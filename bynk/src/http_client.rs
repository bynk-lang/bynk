//! `bynk client` (#3508, BC1): a typed TypeScript client for a project's `from
//! http` services.
//!
//! The routes, their parameters and their response sets are the facts `bynk
//! openapi` reads (the wire-contract peek, `bynk_ide::wire_contract`), so the two
//! cannot disagree on a status or a shape. This module collects them into the
//! generator's input (`bynk_emit::emitter::http_client`) and writes the result.
//!
//! A route the first version cannot represent faithfully is named and left out,
//! never emitted wrong: a raw `RequestQuery` or `RequestCookies` view, and a route
//! guarded by a request signature (the client holds no secret).

use bynk_driver::colour;
use bynk_driver::emsg;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use bynk_emit::emitter::http_client::{
    BodyKind, ClientError, DIR_FILES, HttpClientInput, Layout, ParamInput, ReplyInput,
    ReplyPayload, RouteInput, ServiceInput, emit_http_client,
};
use bynk_ide::wire_contract::{
    BoundaryKind, IrHttpMethod, ResponseOrigin, WireContractModel, real_context_count,
    wire_contract_for_service,
};
use bynk_ide::{ContextBoundaryInfo, ProjectDiagnostics};
use bynk_model::{IrHandlerKind, lower_handler_kind_ir};
use bynk_syntax::ast::{
    ErrorFormat, Handler, HttpVariantPayload, TypeRef, effective_error_format, http_variant,
};

use crate::openapi::{self, Error as ProjectError, Selected};

/// Why a client could not be produced.
#[derive(Debug)]
pub enum Error {
    /// The project does not check, names no such service, or has none.
    Project(ProjectError),
    /// Every route of the selected services is one this version cannot represent.
    NothingToGenerate(Vec<String>),
    /// The generator refused.
    Generate(ClientError),
}

impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Error::Project(e) => e.fmt(f),
            Error::Generate(e) => e.fmt(f),
            Error::NothingToGenerate(skipped) => {
                write!(
                    f,
                    "no route of the selected services is one this version of `bynk client` can represent"
                )?;
                for s in skipped {
                    write!(f, "\n  {s}")?;
                }
                Ok(())
            }
        }
    }
}

impl std::error::Error for Error {}

/// The generated files and the routes they leave out, with why.
#[derive(Debug)]
pub struct Client {
    /// `(file name, text)`: one file, or the four of a directory layout.
    pub files: Vec<(String, String)>,
    pub skipped: Vec<String>,
}

/// What `bynk client` was asked, from its flags. A flag left out falls back to
/// `[build.client]` in `bynk.toml`.
#[derive(Debug, Default)]
pub struct Request<'a> {
    pub services: &'a [String],
    pub out: Option<&'a Path>,
    pub layout: Option<Layout>,
    pub check: bool,
}

/// `bynk client`: analyse the project at `root`, then write the client, or (with
/// `check`) say whether what is written is current.
pub fn run(root: &Path, req: Request) -> ExitCode {
    let config = match bynk_project::try_read_build_config(root) {
        Ok(c) => c.client,
        Err(e) => {
            emsg!("bynk: error: {e}");
            return ExitCode::FAILURE;
        }
    };
    let layout = req
        .layout
        .or_else(|| config.as_ref().map(|c| to_layout(c.layout)))
        .unwrap_or_default();
    let out: Option<PathBuf> = req
        .out
        .map(Path::to_path_buf)
        .or_else(|| config.as_ref().map(|c| root.join(&c.out)));
    let services: Vec<String> = if req.services.is_empty() {
        config.map(|c| c.services).unwrap_or_default()
    } else {
        req.services.to_vec()
    };
    if let Err(e) = check_destination(out.as_deref(), layout, req.check) {
        emsg!("bynk: error: {e}");
        return ExitCode::FAILURE;
    }
    let names: Vec<&str> = services.iter().map(String::as_str).collect();
    let analysis = openapi::analyse(root);
    let client = match generate(&analysis, &names, layout) {
        Ok(c) => c,
        Err(e) => {
            emsg!("bynk: error: {e}");
            return ExitCode::FAILURE;
        }
    };
    for s in &client.skipped {
        emsg!("bynk: warning: skipped {s}");
    }
    match (out, req.check) {
        (None, _) => {
            print!("{}", client.files[0].1);
            ExitCode::SUCCESS
        }
        (Some(out), true) => check(&client, &out, layout),
        (Some(out), false) => match write(&client, &out, layout) {
            Ok(()) => ExitCode::SUCCESS,
            Err(e) => {
                emsg!("bynk: error: {e}");
                ExitCode::FAILURE
            }
        },
    }
}

/// The first line of every file `bynk client` writes.
const GENERATED: &str = "// @generated by `bynk client`";

/// A directory layout's files are the four of [`DIR_FILES`]; a `.ts` file beside them
/// is probably what an earlier layout left, and `--check` cannot see it.
fn note_extra_files(out: &Path, layout: Layout) {
    if layout != Layout::Dir {
        return;
    }
    let Ok(entries) = std::fs::read_dir(out) else {
        return;
    };
    let mut extra: Vec<String> = entries
        .flatten()
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .filter(|n| n.ends_with(".ts") && !DIR_FILES.contains(&n.as_str()))
        .collect();
    extra.sort();
    for name in extra {
        emsg!(
            "bynk: note: `{}` is not part of the client; a layout that was replaced may have left it",
            out.join(name).display()
        );
    }
}

/// `bynk build`'s share (#3508, `[build.client]`): write the client when the
/// manifest asks for one, and say so. Nothing happens, and nothing is read
/// beyond the manifest, when it does not.
pub fn write_configured(root: &Path) -> ExitCode {
    match bynk_project::try_read_build_config(root) {
        Ok(c) if c.client.is_some() => {}
        Ok(_) => return ExitCode::SUCCESS,
        Err(e) => {
            emsg!("bynk: error: {e}");
            return ExitCode::FAILURE;
        }
    }
    let code = run(root, Request::default());
    if code == ExitCode::SUCCESS
        && let Ok(Some(c)) = bynk_project::try_read_build_config(root).map(|c| c.client)
    {
        emsg!("bynk: wrote the client -> {}", root.join(c.out).display());
    }
    code
}

fn to_layout(l: bynk_project::ClientLayout) -> Layout {
    match l {
        bynk_project::ClientLayout::File => Layout::File,
        bynk_project::ClientLayout::Dir => Layout::Dir,
    }
}

/// Whether the client can go where it was asked to.
fn check_destination(out: Option<&Path>, layout: Layout, check: bool) -> Result<(), String> {
    match (out, layout) {
        (None, _) if check => Err(
            "`--check` compares with a written client: pass `--out PATH`, or set `[build.client]` in bynk.toml"
                .to_string(),
        ),
        (None, Layout::Dir) => {
            Err("`--layout dir` writes several files: pass `--out DIR`".to_string())
        }
        (Some(out), Layout::File) if out.is_dir() => Err(format!(
            "`{}` is a directory; pass a file, or `--layout dir`",
            out.display()
        )),
        (Some(out), Layout::Dir) if out.is_file() => Err(format!(
            "`{}` is a file; `--layout dir` writes a directory",
            out.display()
        )),
        _ => Ok(()),
    }
}

/// The paths a client's files go to.
fn destinations(client: &Client, out: &Path, layout: Layout) -> Vec<(PathBuf, String)> {
    match layout {
        Layout::File => vec![(out.to_path_buf(), client.files[0].1.clone())],
        Layout::Dir => client
            .files
            .iter()
            .map(|(name, text)| (out.join(name), text.clone()))
            .collect(),
    }
}

/// Write the client, leaving a file alone whose text is already right so a watcher
/// does not see a change that is not one.
fn write(client: &Client, out: &Path, layout: Layout) -> Result<(), String> {
    let targets = destinations(client, out, layout);
    // Nothing is written until every destination is known to be ours to replace: a
    // `[build.client] out` that names another file (`../.bashrc`) must not lose it.
    for (path, _) in &targets {
        if let Ok(have) = std::fs::read(path)
            && !have.starts_with(GENERATED.as_bytes())
        {
            return Err(format!(
                "refusing to overwrite `{}`: it is not a client `bynk client` wrote (its first line is not `{GENERATED}`)",
                path.display()
            ));
        }
    }
    note_extra_files(out, layout);
    for (path, text) in targets {
        if std::fs::read_to_string(&path).is_ok_and(|have| have == text) {
            continue;
        }
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir)
                .map_err(|e| format!("cannot create {}: {e}", dir.display()))?;
        }
        std::fs::write(&path, text).map_err(|e| format!("cannot write {}: {e}", path.display()))?;
    }
    Ok(())
}

/// `--check`: the written client against the one the project generates now.
fn check(client: &Client, out: &Path, layout: Layout) -> ExitCode {
    let mut stale = Vec::new();
    for (path, want) in destinations(client, out, layout) {
        match std::fs::read_to_string(&path) {
            Err(_) => stale.push(format!("  {}: missing", path.display())),
            Ok(have) => {
                if let Some(d) = short_diff(&path, &want, &have) {
                    stale.push(d);
                }
            }
        }
    }
    note_extra_files(out, layout);
    if stale.is_empty() {
        return ExitCode::SUCCESS;
    }
    let dir = if layout == Layout::Dir {
        " --layout dir"
    } else {
        ""
    };
    emsg!(
        "bynk: error: client is stale: run `bynk client{dir} --out {}`",
        out.display()
    );
    for line in stale {
        colour::eprintln(&line);
    }
    ExitCode::FAILURE
}

/// `text` without the header line that names the compiler's version: a compiler
/// upgrade alone does not make a client stale.
fn without_version(text: &str) -> String {
    text.lines()
        .filter(|l| !(l.starts_with("// bynk ") && l.contains(". Regenerate with `bynk client`;")))
        .collect::<Vec<_>>()
        .join("\n")
}

/// Where `have` first differs from `want`, in a few lines; `None` when they are the
/// same text. Line endings do not count: a checkout may rewrite them.
fn short_diff(path: &Path, want: &str, have: &str) -> Option<String> {
    let norm = |t: &str| without_version(&t.replace("\r\n", "\n"));
    let (want, have) = (norm(want), norm(have));
    if want == have {
        return None;
    }
    let (w, h): (Vec<&str>, Vec<&str>) = (want.lines().collect(), have.lines().collect());
    let first = (0..w.len().max(h.len()))
        .find(|&i| w.get(i) != h.get(i))
        .unwrap_or(0);
    let differing = (0..w.len().max(h.len()))
        .filter(|&i| w.get(i) != h.get(i))
        .count();
    let show = |l: Option<&&str>| l.map_or("<end of file>".to_string(), |l| l.to_string());
    Some(format!(
        "  {} differs at line {} ({differing} line{} in all):\n    - found:    {}\n    + expected: {}",
        path.display(),
        first + 1,
        if differing == 1 { "" } else { "s" },
        show(h.get(first)),
        show(w.get(first)),
    ))
}

/// The client for `analysis`' `from http` services named by `want` (every one when
/// empty).
pub fn generate(
    analysis: &ProjectDiagnostics,
    want: &[&str],
    layout: Layout,
) -> Result<Client, Error> {
    let errors = openapi::errors_of(analysis);
    if !errors.is_empty() {
        return Err(Error::Project(ProjectError::Invalid(errors)));
    }
    let selected = openapi::select_services(analysis, want).map_err(Error::Project)?;
    let context_count = real_context_count(&analysis.boundary_info, &analysis.unit_sources);
    let mut services = Vec::new();
    let mut skipped = Vec::new();
    for sel in &selected {
        let routes = routes_of(analysis, sel, context_count, &mut skipped);
        if routes.is_empty() {
            continue;
        }
        services.push(ServiceInput {
            unit: sel.unit.to_string(),
            name: sel.service.name.name.clone(),
            doc: sel
                .service
                .documentation
                .as_ref()
                .map(|d| d.text.trim().to_string()),
            types: sel.info.types.clone(),
            routes,
        });
    }
    if services.is_empty() {
        return Err(Error::NothingToGenerate(skipped));
    }
    let input = HttpClientInput {
        services,
        compiler_version: env!("CARGO_PKG_VERSION").to_string(),
    };
    let emitted = emit_http_client(&input, layout).map_err(Error::Generate)?;
    skipped.extend(emitted.skipped);
    Ok(Client {
        files: emitted.files,
        skipped,
    })
}

/// A service's routes this version represents; the others go to `skipped`.
fn routes_of(
    analysis: &ProjectDiagnostics,
    sel: &Selected,
    context_count: usize,
    skipped: &mut Vec<String>,
) -> Vec<RouteInput> {
    let expr_types = unit_expr_types(analysis, sel.unit);
    let mut routes = Vec::new();
    for h in &sel.service.handlers {
        if !matches!(lower_handler_kind_ir(&h.kind), IrHandlerKind::Http { .. }) {
            continue;
        }
        let Some(model) = wire_contract_for_service(
            sel.unit,
            "",
            &sel.service.name.name,
            h,
            sel.info,
            &expr_types,
            &analysis.ty_intern,
            context_count,
        ) else {
            continue;
        };
        let BoundaryKind::Http { method, path } = &model.kind else {
            continue;
        };
        match route_of(sel, h, &model, *method, path) {
            Ok(r) => routes.push(r),
            Err(why) => skipped.push(format!(
                "`{} {path}` of `{}`: {why}",
                method.as_str(),
                sel.service.name.name
            )),
        }
    }
    routes
}

/// Every file of `unit`'s checked expression types, as `bynk openapi` reads them.
fn unit_expr_types(
    analysis: &ProjectDiagnostics,
    unit: &str,
) -> Vec<(bynk_syntax::span::Span, bynk_check::checker::TyId)> {
    analysis
        .unit_sources
        .get(unit)
        .into_iter()
        .flatten()
        .filter_map(|p| analysis.expr_types.get(p))
        .flatten()
        .cloned()
        .collect()
}

/// One route as the generator takes it, or why this version leaves it out.
fn route_of(
    sel: &Selected,
    h: &Handler,
    model: &WireContractModel,
    method: IrHttpMethod,
    path: &str,
) -> Result<RouteInput, String> {
    unsupported(sel.info, h)?;
    let in_path: Vec<&str> = path
        .split('/')
        .filter_map(|s| s.strip_prefix(':'))
        .collect();
    let mut params = Vec::new();
    for p in &h.params {
        let name = p.name.name.as_str();
        if name == "body" {
            params.push(ParamInput::Body {
                ty: p.type_ref.clone(),
                kind: body_kind(h),
            });
        } else if in_path.contains(&name) {
            params.push(ParamInput::Path {
                name: name.to_string(),
                ty: p.type_ref.clone(),
            });
        } else if name == "query" && matches!(p.type_ref, TypeRef::Named(_)) {
            params.push(ParamInput::Query {
                ty: p.type_ref.clone(),
            });
        } else if name == "cookies" && matches!(p.type_ref, TypeRef::Named(_)) {
            params.push(ParamInput::Cookies {
                ty: p.type_ref.clone(),
            });
        } else if name == "headers" && matches!(p.type_ref, TypeRef::Named(_)) {
            params.push(ParamInput::Headers {
                ty: p.type_ref.clone(),
            });
        }
        // The raw `query`, `cookies` and `headers` views declare nothing a caller supplies.
    }
    let success = match success_of(h) {
        Some(TypeRef::Unit(_)) | None => None,
        Some(t) => Some(t.clone()),
    };
    Ok(RouteInput {
        method: method.as_str().to_string(),
        path: path.to_string(),
        doc: h.documentation.as_ref().map(|d| d.text.trim().to_string()),
        params,
        success,
        replies: replies_of(
            model,
            effective_error_format(sel.service.errors.as_ref(), h) == ErrorFormat::Problem,
        )?,
    })
}

/// The route's features this version cannot represent, if any.
fn unsupported(info: &ContextBoundaryInfo, h: &Handler) -> Result<(), String> {
    if h.params
        .iter()
        .any(|p| p.name.name == "query" && matches!(p.type_ref, TypeRef::RequestQuery(_)))
    {
        return Err("a raw `query: RequestQuery` is not supported yet".to_string());
    }
    if h.params
        .iter()
        .any(|p| p.name.name == "cookies" && matches!(p.type_ref, TypeRef::RequestCookies(_)))
    {
        return Err("a raw `cookies: RequestCookies` is not supported yet".to_string());
    }
    if bynk_check::actors::signature_seam_for(h, &info.actors).is_some() {
        return Err(
            "the route is guarded by a request signature, which a client without the secret cannot make"
                .to_string(),
        );
    }
    Ok(())
}

/// How the route reads its `body`: JSON, unless it is a `@form` or `@multipart` one.
fn body_kind(h: &Handler) -> BodyKind {
    if h.annotations.iter().any(|a| a.name.name == "raw") {
        return BodyKind::Raw {
            content_type: h
                .raw_content_type()
                .filter(|ct| *ct != "*/*")
                .map(str::to_string),
        };
    }
    let note = |name: &str| h.annotations.iter().any(|a| a.name.name == name);
    if note("multipart") {
        BodyKind::Multipart
    } else if note("form") {
        BodyKind::Form
    } else {
        BodyKind::Json
    }
}

/// `Effect[HttpResult[T]]` or `HttpResult[T]` to `T`.
fn success_of(h: &Handler) -> Option<&TypeRef> {
    let t = match &h.return_type {
        TypeRef::Effect(inner, _) => inner.as_ref(),
        other => other,
    };
    match t {
        TypeRef::HttpResult(inner, _) => Some(inner.as_ref()),
        _ => None,
    }
}

/// The answers the handler can make: the set `bynk openapi` documents.
fn replies_of(model: &WireContractModel, problem: bool) -> Result<Vec<ReplyInput>, String> {
    let mut out = Vec::new();
    for resp in &model.responses {
        if resp.origin == ResponseOrigin::DeclaredSuccess && !model.ok_reachable {
            continue;
        }
        let payload = if let ResponseOrigin::BoundaryImplicit { .. } = &resp.origin {
            match resp.variant.as_str() {
                "StructuralMismatch" | "PayloadTooLarge" | "UnsupportedMediaType" if problem => {
                    ReplyPayload::Problem
                }
                "StructuralMismatch" => ReplyPayload::BoundaryError,
                "PayloadTooLarge" | "UnsupportedMediaType" => ReplyPayload::BoundaryRefusal,
                _ => continue,
            }
        } else {
            let Some(v) = http_variant(&resp.variant) else {
                continue;
            };
            match v.payload {
                HttpVariantPayload::Value => ReplyPayload::Value,
                HttpVariantPayload::Message if problem => ReplyPayload::Problem,
                HttpVariantPayload::Message => ReplyPayload::Message,
                HttpVariantPayload::Location => ReplyPayload::Location,
                HttpVariantPayload::None => ReplyPayload::None,
                HttpVariantPayload::Streamed => ReplyPayload::Events,
                HttpVariantPayload::RawTagged => ReplyPayload::RawTagged,
                HttpVariantPayload::Raw if resp.variant == "Raw" => ReplyPayload::RawEtag,
                HttpVariantPayload::Raw
                | HttpVariantPayload::RawStreamed
                | HttpVariantPayload::RawError => ReplyPayload::Raw,
            }
        };
        out.push(ReplyInput {
            status: resp.status,
            variant: resp.variant.clone(),
            payload,
        });
    }
    Ok(out)
}

//! `bynk client` (#3508, BC1): the typed TypeScript client for a project's `from
//! http` services.
//!
//! Goldens pin the generated module for the `shapes` project `bynk openapi`
//! pins (`BYNK_BLESS=1 cargo test -p bynk` re-blesses them) and for `rich`, which
//! adds what a front end meets: `Option` as `T | null`, an opaque id, a generic
//! page, a typed `query` with defaults and a `@name`, `Decimal` and `Instant`.
//! Beside them: the command's surface (`--out`, `--service`, the refusals), a
//! route this version leaves out is named, and the output is byte-identical
//! between runs. Whether the module type-checks and what it does against a real
//! Worker is `bynk-tests`' `system::http_client`.

use std::path::{Path, PathBuf};
use std::process::Command;

fn bynk() -> PathBuf {
    PathBuf::from(env!("CARGO_BIN_EXE_bynk"))
}

fn manifest_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn fixture(name: &str) -> PathBuf {
    manifest_dir().join("tests/fixtures/http_client").join(name)
}

fn shapes() -> PathBuf {
    manifest_dir().join("tests/fixtures/openapi/shapes")
}

fn scratch(name: &str) -> PathBuf {
    let dir = PathBuf::from(env!("CARGO_TARGET_TMPDIR")).join(format!("http-client-{name}"));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

/// `bynk client <args>` to (success, stdout, stderr).
fn client(args: &[&str]) -> (bool, String, String) {
    let out = Command::new(bynk())
        .arg("client")
        .args(args)
        .output()
        .expect("run bynk");
    (
        out.status.success(),
        String::from_utf8_lossy(&out.stdout).into_owned(),
        String::from_utf8_lossy(&out.stderr).into_owned(),
    )
}

fn module(path: &Path, extra: &[&str]) -> String {
    let mut args = vec![path.to_str().unwrap()];
    args.extend_from_slice(extra);
    let (ok, stdout, stderr) = client(&args);
    assert!(ok, "bynk client failed: {stderr}");
    versionless(&stdout)
}

/// The header names the compiler's version, which a golden must not pin: it would go
/// stale at every release. Only the version is replaced, so the rest of the header (the
/// reference URL) and the file's line endings stay under the byte-for-byte check, and a
/// header that did not carry the real version would fail to match here.
fn versionless(text: &str) -> String {
    let header = format!("// bynk {}. ", env!("CARGO_PKG_VERSION"));
    assert!(
        text.contains(&header),
        "the header names the compiler's version: {:?}",
        text.lines().nth(1)
    );
    text.replacen(&header, "// bynk <version>. ", 1)
}

fn golden(name: &str, actual: &str) {
    let path = manifest_dir().join("tests/golden").join(name);
    if std::env::var_os("BYNK_BLESS").is_some() {
        std::fs::write(&path, actual).unwrap();
        return;
    }
    let expected = std::fs::read_to_string(&path).unwrap_or_else(|_| {
        panic!("missing golden {name}; regenerate with BYNK_BLESS=1 cargo test -p bynk")
    });
    assert_eq!(
        expected, actual,
        "golden {name} drifted; re-bless with BYNK_BLESS=1 cargo test -p bynk"
    );
}

#[test]
fn the_shapes_project_client_is_pinned() {
    golden("http_client_shapes.ts", &module(&shapes(), &[]));
}

#[test]
fn the_rich_project_client_is_pinned() {
    golden("http_client_rich.ts", &module(&fixture("rich"), &[]));
}

#[test]
fn the_output_is_byte_identical_between_runs() {
    let a = module(&fixture("rich"), &[]);
    let b = module(&fixture("rich"), &[]);
    assert_eq!(a, b);
}

#[test]
fn out_writes_the_module_and_stdout_stays_empty() {
    let dir = scratch("out");
    let file = dir.join("api.ts");
    let (ok, stdout, stderr) = client(&[
        fixture("one").to_str().unwrap(),
        "--out",
        file.to_str().unwrap(),
    ]);
    assert!(ok, "{stderr}");
    assert!(stdout.is_empty());
    let text = std::fs::read_to_string(&file).unwrap();
    assert!(text.starts_with("// @generated by `bynk client`"));
    assert!(text.contains("export function createClient("));
    assert!(text.contains("getHelloByName"), "{text}");
}

#[test]
fn a_service_narrows_the_client() {
    let all = module(&fixture("rich"), &[]);
    let one = module(&fixture("rich"), &["--service", "api"]);
    assert_eq!(all, one, "the only service is `api`");
    let by_unit = module(&fixture("rich"), &["--service", "rich.api"]);
    assert_eq!(all, by_unit);
}

#[test]
fn an_unknown_service_is_refused_naming_the_known_ones() {
    let (ok, _, stderr) = client(&[fixture("rich").to_str().unwrap(), "--service", "nope"]);
    assert!(!ok);
    assert!(
        stderr.contains("no `from http` service `nope`") && stderr.contains("api"),
        "{stderr}"
    );
}

#[test]
fn a_project_that_does_not_check_is_refused() {
    let dir = scratch("broken");
    std::fs::create_dir_all(dir.join("src")).unwrap();
    std::fs::write(
        dir.join("bynk.toml"),
        "[project]\nname = \"broken\"\nversion = \"0.1.0\"\n",
    )
    .unwrap();
    std::fs::write(
        dir.join("src/broken.bynk"),
        "context broken\n\ntype = oops\n",
    )
    .unwrap();
    let (ok, stdout, stderr) = client(&[dir.to_str().unwrap()]);
    assert!(!ok);
    assert!(stdout.is_empty());
    assert!(stderr.contains("the project has errors"), "{stderr}");
}

#[test]
fn a_route_this_version_cannot_represent_is_named_and_left_out() {
    let (ok, stdout, stderr) = client(&[fixture("skipped").to_str().unwrap()]);
    assert!(ok, "{stderr}");
    assert!(stderr.contains("skipped `POST /blob` of `api`: a `@raw` body"));
    assert!(stderr.contains("skipped `POST /note` of `api`: a `@form` or `@multipart` body"));
    assert!(stderr.contains("skipped `GET /raw` of `api`: a raw `query: RequestQuery`"));
    assert!(stdout.contains("getPing") && !stdout.contains("getRaw"));
    assert!(!stdout.contains("postBlob") && !stdout.contains("postNote"));
}

#[test]
fn a_project_with_no_http_service_is_refused() {
    let dir = scratch("none");
    std::fs::create_dir_all(dir.join("src")).unwrap();
    std::fs::write(
        dir.join("bynk.toml"),
        "[project]\nname = \"none\"\nversion = \"0.1.0\"\n",
    )
    .unwrap();
    std::fs::write(
        dir.join("src/none.bynk"),
        "context none\n\ntype Id = String\n",
    )
    .unwrap();
    let (ok, _, stderr) = client(&[dir.to_str().unwrap()]);
    assert!(!ok);
    assert!(stderr.contains("no `from http` service"), "{stderr}");
}

#[test]
fn a_refinement_violation_message_names_the_declared_type() {
    let text = module(&shapes(), &[]);
    assert!(
        !text.contains("field: \"__Wire_"),
        "a violation names the declared type, not its wire alias"
    );
    assert!(text.contains("field: \"Sku\""));
}

#[test]
fn build_writes_the_client_the_manifest_asks_for_and_otherwise_nothing() {
    let with = project_with("build-with", "\n[build.client]\nout = \"web/api.ts\"\n");
    let out = Command::new(bynk())
        .args(["build", "--target", "workers"])
        .arg(&with)
        .output()
        .expect("run bynk");
    assert!(
        out.status.success(),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
    assert!(with.join("web/api.ts").is_file());
    assert!(String::from_utf8_lossy(&out.stderr).contains("wrote the client"));

    let without = project_with("build-without", "");
    let out = Command::new(bynk())
        .args(["build", "--target", "workers"])
        .arg(&without)
        .output()
        .expect("run bynk");
    assert!(out.status.success());
    let mut files = Vec::new();
    fn walk(dir: &Path, files: &mut Vec<PathBuf>) {
        for e in std::fs::read_dir(dir).unwrap().flatten() {
            if e.path().is_dir() {
                walk(&e.path(), files);
            } else {
                files.push(e.path());
            }
        }
    }
    walk(&without, &mut files);
    assert!(
        files.iter().all(|f| f.extension().is_none_or(|e| e != "ts")
            || f.strip_prefix(&without)
                .is_ok_and(|rel| rel.starts_with("out"))),
        "a project without `[build.client]` gains no client: {files:?}"
    );
}

#[test]
fn a_file_that_is_not_a_generated_client_is_never_overwritten() {
    // The manifest's `out` may leave the project, so a build must not replace what
    // it did not write.
    let project = project_with("overwrite", "\n[build.client]\nout = \"precious.txt\"\n");
    let precious = project.join("precious.txt");
    std::fs::write(&precious, "my notes\n").unwrap();
    let (ok, _, stderr) = client(&[project.to_str().unwrap()]);
    assert!(!ok);
    assert!(stderr.contains("refusing to overwrite"), "{stderr}");
    assert_eq!(std::fs::read_to_string(&precious).unwrap(), "my notes\n");
    // A client of its own is replaced, and a stale one too.
    std::fs::remove_file(&precious).unwrap();
    assert!(client(&[project.to_str().unwrap()]).0);
    std::fs::write(
        &precious,
        format!("// @generated by `bynk client`\n{}", "stale"),
    )
    .unwrap();
    assert!(client(&[project.to_str().unwrap()]).0);
    assert!(
        std::fs::read_to_string(&precious)
            .unwrap()
            .contains("createClient")
    );
}


//! #4235: shared generated sources are snapshotted once, not once per fixture.
//!
//! A fixture's emitted output carries whole copies of sources that no fixture owns: the
//! standard library's adapters and commons (`bynk.ts`, `bynk-cloudflare.ts`, `bynk/**`) and the
//! test runtime spliced into every `*.test.ts` (`testgen/test_runtime/*.ts`). Each such region
//! is replaced, in the fixture's `expected/` tree, by a marker naming the module:
//!
//! ```text
//! <<bynk-shared: std/bynk.ts#bytes+errors+result>>
//! <<bynk-shared: testing/expectation>>
//! ```
//!
//! The marker carries **no content hash**, so a change to a shared source rewrites only its one
//! snapshot under `tests/fixtures/shared/`. The harness still checks every byte: the region a
//! fixture really emits must equal that shared snapshot, and the rest of the file must equal the
//! fixture's snapshot. Nothing is excluded from comparison; the emitter's output is unchanged.
//!
//! How a region is found:
//!
//! - **Standard-library files** are whole files. They are identified by their emitted path
//!   (`bynk.ts`, `bynk-cloudflare.ts`, anything under `bynk/`, the reserved namespace) and by the
//!   emitter's own header (`// Generated by bynk`, then `// adapter …` / `// commons bynk…` /
//!   `// bynk…`). The *variant* is the sorted set of `__bynk_runtime/*` modules the file
//!   imports, because the emitter prunes imports and serialisers per project. Adding or
//!   removing a runtime import in a std module therefore renames its variant.
//! - **Test-runtime fragments** are spliced verbatim with no emitter-written delimiter. They
//!   are found by exact match of the current `testgen/test_runtime/<name>.ts` text. A fixture
//!   carrying a changed or partial copy is not elided, so it fails the byte comparison.

// Each file that includes this module uses a part of it (see `it.rs` on `#[path]` helpers).
#![allow(dead_code)]

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

const OPEN: &str = "<<bynk-shared: ";
const CLOSE: &str = ">>";

/// `tests/fixtures/shared/`, where each shared region has one snapshot.
pub fn shared_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("fixtures")
        .join("shared")
}

fn marker(id: &str) -> String {
    format!("{OPEN}{id}{CLOSE}")
}

/// The snapshot file of a shared region: `std/bynk/locale/types#a+b` is
/// `shared/std/bynk/locale/types@a+b.ts`; `testing/expectation` is `shared/testing/expectation.ts`.
fn snapshot_path(id: &str) -> PathBuf {
    let (base, variant) = match id.split_once('#') {
        Some((b, v)) => (b, Some(v)),
        None => (id, None),
    };
    let base = base.strip_suffix(".ts").unwrap_or(base);
    let file = match variant {
        Some(v) => format!("{base}@{v}.ts"),
        None => format!("{base}.ts"),
    };
    shared_root().join(file)
}

/// The test-runtime fragments, longest first so one that contains another claims it first.
fn fragments() -> Vec<(String, String)> {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("bynk-emit")
        .join("src")
        .join("testgen")
        .join("test_runtime");
    let mut out: Vec<(String, String)> = fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("could not read {}: {e}", dir.display()))
        .flatten()
        .filter_map(|e| {
            let p = e.path();
            let stem = p.file_stem()?.to_str()?.to_string();
            (p.extension()? == "ts")
                .then(|| (format!("testing/{stem}"), fs::read_to_string(&p).unwrap()))
        })
        .filter(|(_, text)| !text.trim().is_empty())
        .collect();
    out.sort_by(|a, b| b.1.len().cmp(&a.1.len()).then(a.0.cmp(&b.0)));
    out
}

fn is_std_path(rel: &Path) -> bool {
    matches!(rel.to_str(), Some("bynk.ts") | Some("bynk-cloudflare.ts"))
        || (rel.starts_with("bynk") && rel.components().count() > 1)
}

/// Whether `text` opens with the header the emitter writes on a std adapter, commons or binding.
fn has_std_header(text: &str) -> bool {
    let mut lines = text.lines();
    lines.next() == Some("// Generated by bynk — do not edit by hand.")
        && lines.next().is_some_and(|l| {
            l.starts_with("// adapter bynk")
                || l.starts_with("// commons bynk")
                || l.starts_with("// bynk")
        })
}

/// The sorted `__bynk_runtime/<module>.js` modules `text` imports.
fn runtime_variant(text: &str) -> String {
    let mut mods: Vec<&str> = text
        .lines()
        .filter(|l| l.starts_with("import "))
        .filter_map(|l| {
            let at = l.find("__bynk_runtime/")? + "__bynk_runtime/".len();
            l[at..].split(".js").next()
        })
        .collect();
    mods.sort();
    mods.dedup();
    if mods.is_empty() {
        "none".into()
    } else {
        mods.join("+")
    }
}

/// A file with its shared regions replaced by markers, and the regions it held.
pub struct Elided {
    pub text: String,
    /// `(id, real region text)` in the order found.
    pub regions: Vec<(String, String)>,
}

/// Replace every shared region of one emitted file (`rel` is its path under the output root).
pub fn elide(rel: &Path, text: &str) -> Elided {
    if is_std_path(rel) && has_std_header(text) {
        let base = rel.to_str().unwrap().replace('\\', "/");
        let id = format!("std/{base}#{}", runtime_variant(text));
        return Elided {
            text: format!("{}\n", marker(&id)),
            regions: vec![(id, text.to_string())],
        };
    }
    let mut out = text.to_string();
    let mut regions = Vec::new();
    let is_test_module = rel.starts_with("tests") && rel.extension().is_some_and(|e| e == "ts");
    if is_test_module {
        for (id, frag) in fragments() {
            // A marker is a whole line, so a fragment is elided only where that round-trips:
            // it ends in a newline and starts at the start of a line.
            let Some(at) = out.find(&frag) else { continue };
            let at_line_start = at == 0 || out.as_bytes()[at - 1] == b'\n';
            if frag.ends_with('\n') && at_line_start && out.matches(&frag).count() == 1 {
                out.replace_range(at..at + frag.len(), &format!("{}\n", marker(&id)));
                regions.push((id, frag));
            }
        }
    }
    Elided { text: out, regions }
}

/// Check each region a fixture emitted against its shared snapshot, byte for byte. Returns one
/// failure line per mismatch.
pub fn check_regions(regions: &[(String, String)]) -> Vec<String> {
    let mut failures = Vec::new();
    for (id, region) in regions {
        let path = snapshot_path(id);
        match fs::read_to_string(&path) {
            Ok(want) if want == *region => {}
            Ok(want) => failures.push(format!(
                "shared `{id}` differs from {}\n--- shared snapshot ---\n{want}\n--- emitted ---\n{region}\n",
                path.display()
            )),
            Err(_) => failures.push(format!(
                "no shared snapshot for `{id}` ({}); bless it",
                path.display()
            )),
        }
    }
    failures
}

/// Accumulates the regions of a whole bless run, so each shared snapshot is written once.
#[derive(Default)]
pub struct SharedBless {
    regions: BTreeMap<String, (String, String)>,
}

impl SharedBless {
    /// Record `regions` from `fixture`; two fixtures emitting different bytes for one id is a
    /// real divergence that no marker can hide, so it panics.
    pub fn record(&mut self, fixture: &Path, regions: Vec<(String, String)>) {
        for (id, text) in regions {
            match self.regions.get(&id) {
                Some((first, seen)) if *seen != text => panic!(
                    "bless: `{id}` is not shared: {} and {} emit different bytes for it",
                    first,
                    fixture.display()
                ),
                Some(_) => {}
                None => {
                    self.regions
                        .insert(id, (fixture.display().to_string(), text));
                }
            }
        }
    }

    /// Rewrite `tests/fixtures/shared/` to exactly the regions recorded.
    pub fn write(self) {
        let root = shared_root();
        let _ = fs::remove_dir_all(&root);
        for (id, (_, text)) in self.regions {
            let path = snapshot_path(&id);
            fs::create_dir_all(path.parent().unwrap()).unwrap();
            fs::write(path, text).unwrap();
        }
    }
}

/// Read an `expected/` file with its markers expanded to the shared snapshots, for the checks
/// that scan a fixture's whole emitted tree.
pub fn read_expanded(path: &Path) -> String {
    let text = fs::read_to_string(path)
        .unwrap_or_else(|e| panic!("could not read {}: {e}", path.display()));
    expand(&text)
}

/// Replace each marker line in `text` with its shared snapshot.
pub fn expand(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for line in text.split_inclusive('\n') {
        let t = line.trim_end_matches('\n');
        match t.strip_prefix(OPEN).and_then(|r| r.strip_suffix(CLOSE)) {
            Some(id) => {
                let p = snapshot_path(id);
                out.push_str(&fs::read_to_string(&p).unwrap_or_else(|e| {
                    panic!("shared snapshot {} for `{id}` is missing: {e}", p.display())
                }));
            }
            None => out.push_str(line),
        }
    }
    out
}

//! #4235: shared generated sources are snapshotted once, not once per fixture.
//!
//! A fixture's emitted output carries whole copies of sources that no fixture owns: the
//! standard library's adapters and commons (`bynk.ts`, `bynk-cloudflare.ts`, `bynk/**`) and the
//! test runtime spliced into every `*.test.ts` (`testgen/test_runtime/*.ts`). Each such region
//! is replaced, in the fixture's `expected/` tree, by a marker naming the module:
//!
//! ```text
//! <<bynk-shared: std/bynk.ts#bytes+errors+result>>
//! <<bynk-shared: testing/expectation>>
//! ```
//!
//! The marker carries **no content hash**, so a change to a shared source rewrites only its one
//! snapshot under `tests/fixtures/shared/`. The harness still checks every byte: the region a
//! fixture really emits must equal that shared snapshot, and the rest of the file must equal the
//! fixture's snapshot. Nothing is excluded from comparison; the emitter's output is unchanged.
//!
//! How a region is found:
//!
//! - **Standard-library files** are whole files. They are identified by their emitted path
//!   (`bynk.ts`, `bynk-cloudflare.ts`, anything under `bynk/`, the reserved namespace) and by the
//!   emitter's own header (`// Generated by bynk`, then `// adapter …` / `// commons bynk…` /
//!   `// bynk…`). The *variant* is the sorted set of `__bynk_runtime/*` modules the file
//!   imports, because the emitter prunes imports and serialisers per project. Adding or
//!   removing a runtime import in a std module therefore renames its variant.
//! - **The runner's `main()`** (`tests/main.ts`) is delimited by comments the emitter writes
//!   (`bynk:shared-begin test-runner#<variant>` to `bynk:shared-end`); the variant names which
//!   optional parts it carries (`detach`, `generative`, `pg`, `remote`), or `base`. A build whose
//!   fixed part holds something of its own (a snapshot report) is not delimited.
//! - **Test-runtime fragments** are spliced verbatim with no emitter-written delimiter. They
//!   are found by exact match of the current `testgen/test_runtime/<name>.ts` text. A fixture
//!   carrying a changed or partial copy is not elided, so it fails the byte comparison.

// Each file that includes this module uses a part of it (see `it.rs` on `#[path]` helpers).
#![allow(dead_code)]

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicUsize, Ordering};

const OPEN: &str = "<<bynk-shared: ";
const CLOSE: &str = ">>";

/// `tests/fixtures/shared/`, where each shared region has one snapshot.
pub fn shared_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("fixtures")
        .join("shared")
}

fn marker(id: &str) -> String {
    format!("{OPEN}{id}{CLOSE}")
}

/// The snapshot file of a shared region: `std/bynk/locale/types#a+b` is
/// `shared/std/bynk/locale/types@a+b.ts`; `testing/expectation` is `shared/testing/expectation.ts`.
fn snapshot_path(id: &str) -> PathBuf {
    shared_root().join(snapshot_rel(id))
}

/// [`snapshot_path`] relative to the shared root.
fn snapshot_rel(id: &str) -> PathBuf {
    let (base, variant) = match id.split_once('#') {
        Some((b, v)) => (b, Some(v)),
        None => (id, None),
    };
    let base = base.strip_suffix(".ts").unwrap_or(base);
    PathBuf::from(match variant {
        Some(v) => format!("{base}@{v}.ts"),
        None => format!("{base}.ts"),
    })
}

/// The test-runtime fragments, longest first so one that contains another claims it first.
fn fragments() -> Vec<(String, String)> {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("bynk-emit")
        .join("src")
        .join("testgen")
        .join("test_runtime");
    let mut out: Vec<(String, String)> = fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("could not read {}: {e}", dir.display()))
        .flatten()
        .filter_map(|e| {
            let p = e.path();
            let stem = p.file_stem()?.to_str()?.to_string();
            (p.extension()? == "ts")
                .then(|| (format!("testing/{stem}"), fs::read_to_string(&p).unwrap()))
        })
        .filter(|(_, text)| !text.trim().is_empty())
        .collect();
    out.sort_by(|a, b| b.1.len().cmp(&a.1.len()).then(a.0.cmp(&b.0)));
    out
}

fn is_std_path(rel: &Path) -> bool {
    matches!(rel.to_str(), Some("bynk.ts") | Some("bynk-cloudflare.ts"))
        || (rel.starts_with("bynk") && rel.components().count() > 1)
}

/// Whether `text` opens with the header the emitter writes on a std adapter, commons or binding.
fn has_std_header(text: &str) -> bool {
    let mut lines = text.lines();
    lines.next() == Some("// Generated by bynk — do not edit by hand.")
        && lines.next().is_some_and(|l| {
            l.starts_with("// adapter bynk")
                || l.starts_with("// commons bynk")
                || l.starts_with("// bynk")
        })
}

/// The sorted `__bynk_runtime/<module>.js` modules `text` imports.
fn runtime_variant(text: &str) -> String {
    let mut mods: Vec<&str> = text
        .lines()
        .filter(|l| l.starts_with("import "))
        .filter_map(|l| {
            let at = l.find("__bynk_runtime/")? + "__bynk_runtime/".len();
            l[at..].split(".js").next()
        })
        .collect();
    mods.sort();
    mods.dedup();
    if mods.is_empty() {
        "none".into()
    } else {
        mods.join("+")
    }
}

/// A file with its shared regions replaced by markers, and the regions it held.
pub struct Elided {
    pub text: String,
    /// `(id, real region text)` in the order found.
    pub regions: Vec<(String, String)>,
}

/// Replace every shared region of one emitted file (`rel` is its path under the output root).
pub fn elide(rel: &Path, text: &str) -> Elided {
    if is_std_path(rel) && has_std_header(text) {
        let base = rel.to_str().unwrap().replace('\\', "/");
        let id = format!("std/{base}#{}", runtime_variant(text));
        return Elided {
            text: format!("{}\n", marker(&id)),
            regions: vec![(id, text.to_string())],
        };
    }
    let mut out = text.to_string();
    let mut regions = Vec::new();
    if rel == Path::new("tests/main.ts")
        && let Some(found) = take_runner_region(&mut out)
    {
        regions.push(found);
    }
    let is_test_module = rel.starts_with("tests") && rel.extension().is_some_and(|e| e == "ts");
    if is_test_module {
        for (id, frag) in fragments() {
            // A marker is a whole line, so a fragment is elided only where that round-trips:
            // it ends in a newline and starts at the start of a line.
            let Some(at) = out.find(&frag) else { continue };
            let at_line_start = at == 0 || out.as_bytes()[at - 1] == b'\n';
            if frag.ends_with('\n') && at_line_start && out.matches(&frag).count() == 1 {
                out.replace_range(at..at + frag.len(), &format!("{}\n", marker(&id)));
                regions.push((id, frag));
            }
        }
    }
    Elided { text: out, regions }
}

/// The emitter delimits the fixed part of `main()` in `tests/main.ts` itself (#4268):
/// `// bynk:shared-begin test-runner#<variant>` to `// bynk:shared-end`, each on its own line
/// inside the function. Replaces that span, whole lines, with its marker. A runner whose fixed
/// part holds something particular to the build is not delimited, and is left alone.
fn take_runner_region(out: &mut String) -> Option<(String, String)> {
    const BEGIN: &str = "\n  // bynk:shared-begin test-runner#";
    const END: &str = "\n  // bynk:shared-end\n";
    let start = out.find(BEGIN)? + 1;
    let after = start + BEGIN.len() - 1;
    let variant_end = after + out[after..].find('\n')?;
    let variant = out[after..variant_end].to_string();
    let end = variant_end + out[variant_end..].find(END)? + END.len();
    let region = out[start..end].to_string();
    let id = format!("test-runner#{variant}");
    out.replace_range(start..end, &format!("{}\n", marker(&id)));
    Some((id, region))
}

/// Check each region a fixture emitted against its shared snapshot, byte for byte. Returns one
/// failure line per mismatch.
pub fn check_regions(regions: &[(String, String)]) -> Vec<String> {
    let mut failures = Vec::new();
    for (id, region) in regions {
        let path = snapshot_path(id);
        match fs::read_to_string(&path) {
            Ok(want) if want == *region => {}
            Ok(want) => failures.push(format!(
                "shared `{id}` differs from {}\n--- shared snapshot ---\n{want}\n--- emitted ---\n{region}\n",
                path.display()
            )),
            Err(_) => failures.push(format!(
                "no shared snapshot for `{id}` ({}); bless it",
                path.display()
            )),
        }
    }
    failures
}

/// Accumulates the regions of a whole bless run, so each shared snapshot is written once.
#[derive(Default)]
pub struct SharedBless {
    regions: BTreeMap<String, (String, String)>,
}

impl SharedBless {
    /// Record `regions` from `fixture`; two fixtures emitting different bytes for one id is a
    /// real divergence that no marker can hide, so it panics.
    pub fn record(&mut self, fixture: &Path, regions: Vec<(String, String)>) {
        for (id, text) in regions {
            match self.regions.get(&id) {
                Some((first, seen)) if *seen != text => panic!(
                    "bless: `{id}` is not shared: {} and {} emit different bytes for it",
                    first,
                    fixture.display()
                ),
                Some(_) => {}
                None => {
                    self.regions
                        .insert(id, (fixture.display().to_string(), text));
                }
            }
        }
    }

    /// Rewrite `tests/fixtures/shared/` to exactly the regions recorded.
    pub fn write(self) {
        write_snapshots(
            &shared_root(),
            self.regions.into_iter().map(|(id, (_, text))| (id, text)),
        );
    }
}

/// #4540: make `root` hold exactly `regions`, one snapshot file each, without a moment at which
/// a recorded snapshot is missing. Other tests read the snapshots while a bless runs (`expand`,
/// `check_regions`), so the tree is never deleted and rebuilt. A changed snapshot is written to a
/// temporary file beside it and renamed over it, so a reader sees the old bytes or the new ones;
/// an unchanged one is not touched; and only then are the files no recorded region owns, and the
/// directories they leave empty, removed.
fn write_snapshots(root: &Path, regions: impl IntoIterator<Item = (String, String)>) {
    let mut keep = BTreeSet::new();
    for (id, text) in regions {
        let path = root.join(snapshot_rel(&id));
        if fs::read_to_string(&path).is_ok_and(|now| now == text) {
            keep.insert(path);
            continue;
        }
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        let tmp = temporary_beside(&path);
        fs::write(&tmp, &text).unwrap();
        fs::rename(&tmp, &path)
            .unwrap_or_else(|e| panic!("could not move {} into place: {e}", path.display()));
        keep.insert(path);
    }
    remove_unrecorded(root, &keep);
}

/// A file name beside `path` that no other writer uses, for a write that is then renamed into
/// place. It is not a snapshot's name, so a leftover one is removed as unrecorded.
fn temporary_beside(path: &Path) -> PathBuf {
    static NEXT: AtomicUsize = AtomicUsize::new(0);
    let n = NEXT.fetch_add(1, Ordering::Relaxed);
    let name = path.file_name().unwrap().to_string_lossy();
    // The thread too: each test module that includes this file has its own `NEXT`.
    let thread = format!("{:?}", std::thread::current().id());
    let thread: String = thread.chars().filter(char::is_ascii_digit).collect();
    path.with_file_name(format!(".{name}.{}.{thread}.{n}.tmp", std::process::id()))
}

/// Remove every file under `dir` not in `keep`, then every directory that leaves empty.
fn remove_unrecorded(dir: &Path, keep: &BTreeSet<PathBuf>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if entry.file_type().is_ok_and(|t| t.is_dir()) {
            remove_unrecorded(&path, keep);
            // Fails, and is meant to, while the directory still holds a snapshot.
            let _ = fs::remove_dir(&path);
        } else if !keep.contains(&path) {
            let _ = fs::remove_file(&path);
        }
    }
}

/// Read an `expected/` file with its markers expanded to the shared snapshots, for the checks
/// that scan a fixture's whole emitted tree.
pub fn read_expanded(path: &Path) -> String {
    let text = fs::read_to_string(path)
        .unwrap_or_else(|e| panic!("could not read {}: {e}", path.display()));
    expand(&text)
}

/// Replace each marker line in `text` with its shared snapshot.
pub fn expand(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for line in text.split_inclusive('\n') {
        let t = line.trim_end_matches('\n');
        match t.strip_prefix(OPEN).and_then(|r| r.strip_suffix(CLOSE)) {
            Some(id) => {
                let p = snapshot_path(id);
                out.push_str(&fs::read_to_string(&p).unwrap_or_else(|e| {
                    panic!("shared snapshot {} for `{id}` is missing: {e}", p.display())
                }));
            }
            None => out.push_str(line),
        }
    }
    out
}

/// #4540: a bless rewrites the shared snapshots while other tests read them.
#[cfg(test)]
mod write_tests {
    use super::*;
    use std::sync::Arc;
    use std::sync::atomic::AtomicBool;
    use std::thread;

    /// A fresh directory for one test, under the system's temporary directory. Several test
    /// modules include this file, so each copy of a test gets its own.
    fn scratch(name: &str) -> PathBuf {
        let copy = module_path!().replace("::", "-");
        let dir = std::env::temp_dir().join(format!(
            "bynk-shared-snapshots-{name}-{copy}-{}",
            std::process::id()
        ));
        let _ = fs::remove_dir_all(&dir);
        dir
    }

    /// Forty snapshots in five directories, each fifty identical lines naming `generation`.
    fn regions(generation: usize) -> Vec<(String, String)> {
        (0..40)
            .map(|i| {
                (
                    format!("std/bynk/m{}/f{i}#a+b", i % 5),
                    format!("// generation {generation}, file {i}\n").repeat(50),
                )
            })
            .collect()
    }

    /// Readers in parallel with repeated blesses never find a snapshot missing, and never read a
    /// partly written one. The old `write`, which deleted the tree and rewrote it, fails this
    /// within its first few rewrites, so fifty are enough.
    #[test]
    fn a_bless_never_hides_a_snapshot_from_a_parallel_reader() {
        let root = scratch("race");
        write_snapshots(&root, regions(0));
        let paths: Vec<PathBuf> = regions(0)
            .iter()
            .map(|(id, _)| root.join(snapshot_rel(id)))
            .collect();
        let done = Arc::new(AtomicBool::new(false));
        let readers: Vec<_> = (0..4)
            .map(|_| {
                let (paths, done) = (paths.clone(), Arc::clone(&done));
                thread::spawn(move || {
                    let mut reads = 0usize;
                    while !done.load(Ordering::Relaxed) {
                        for p in &paths {
                            let text = fs::read_to_string(p).unwrap_or_else(|e| {
                                panic!("{} is missing during a bless: {e}", p.display())
                            });
                            let first = text.lines().next().unwrap_or_default();
                            assert!(
                                text.lines().count() == 50 && text.lines().all(|l| l == first),
                                "{} was read partly written",
                                p.display()
                            );
                            reads += 1;
                        }
                        thread::yield_now();
                    }
                    reads
                })
            })
            .collect();
        // Stop the readers even if a write panics, so a failure reports instead of hanging.
        struct Stop(Arc<AtomicBool>);
        impl Drop for Stop {
            fn drop(&mut self) {
                self.0.store(true, Ordering::Relaxed);
            }
        }
        let stop = Stop(Arc::clone(&done));
        for generation in 1..=50 {
            write_snapshots(&root, regions(generation));
        }
        drop(stop);
        for reader in readers {
            let reads = reader.join().expect("a reader failed during the blesses");
            assert!(reads > 0, "a reader never ran");
        }
        let _ = fs::remove_dir_all(&root);
    }

    /// A bless removes the snapshots it no longer records, the directories they leave empty and
    /// any leftover temporary file, and leaves an unchanged snapshot untouched.
    #[test]
    fn a_bless_removes_only_what_it_no_longer_records() {
        let root = scratch("stale");
        let stale_id = "std/bynk/gone/old#x";
        let mut first = regions(0);
        first.push((stale_id.to_string(), "old\n".to_string()));
        write_snapshots(&root, first);
        let stale = root.join(snapshot_rel(stale_id));
        assert!(stale.is_file());
        let leftover = root.join("std/bynk/m0/.f0@a+b.ts.1.0.tmp");
        fs::write(&leftover, "partial").unwrap();
        let kept = root.join(snapshot_rel(&regions(0)[0].0));
        let before = fs::metadata(&kept).unwrap().modified().unwrap();

        write_snapshots(&root, regions(0));

        assert!(!stale.exists(), "an unrecorded snapshot is removed");
        assert!(
            !stale.parent().unwrap().exists(),
            "and the directory it left empty"
        );
        assert!(!leftover.exists(), "a leftover temporary file is removed");
        for (id, text) in regions(0) {
            assert_eq!(
                fs::read_to_string(root.join(snapshot_rel(&id))).unwrap(),
                text
            );
        }
        assert_eq!(
            fs::metadata(&kept).unwrap().modified().unwrap(),
            before,
            "an unchanged snapshot is not rewritten"
        );
        let _ = fs::remove_dir_all(&root);
    }
}

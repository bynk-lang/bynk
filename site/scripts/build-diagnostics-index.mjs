// @ts-check
//! Assemble the diagnostic index page from the per-code files (#4286).
//!
//! `src/generated/diagnostics/<code>.json` holds one document per registry code
//! (written by the `diagnostics_registry` docs-consistency test from the compiler's
//! registry, `bynk-syntax/src/diagnostics.rs`). Two changes that add different codes
//! touch different files, so they never conflict. The index page lists every code,
//! grouped by category, so it is built here, at site build time, and never committed:
//! `src/content/docs/reference/diagnostics.md` is gitignored.
//!
//!   node scripts/build-diagnostics-index.mjs    write the index page
//!
//! Run by `npm run build` (`prebuild`) and `npm run dev` (`predev`).

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DIR = path.join(HERE, "../src/generated/diagnostics");
const OUT = path.join(HERE, "../src/content/docs/reference/diagnostics.md");
const INDEX_PATH = "/reference/diagnostics/";

/**
 * @typedef {{ code: string, summary: string, severity: string, category: string }} Entry
 * @typedef {{ code: string, lastRelease: string, why: string, replacement: string | null }} Retired
 */

/** The per-code documents in `dir`, sorted by code. */
export function readEntries(/** @type {string} */ dir) {
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .sort()
    .map((f) => /** @type {Entry} */ (JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"))));
}

/** The tombstones in `<dir>/retired/`, sorted by code; none when the directory is absent (#4277). */
export function readRetired(/** @type {string} */ dir) {
  const sub = path.join(dir, "retired");
  if (!fs.existsSync(sub)) return [];
  return fs
    .readdirSync(sub)
    .filter((f) => f.endsWith(".json"))
    .sort()
    .map((f) => /** @type {Retired} */ (JSON.parse(fs.readFileSync(path.join(sub, f), "utf8"))));
}

/** The index page's Markdown, in the form the Starlight page took when it was committed. */
export function renderIndex(/** @type {Entry[]} */ entries, /** @type {Retired[]} */ retired = []) {
  /** @type {Map<string, Entry[]>} */
  const byCategory = new Map();
  for (const e of [...entries].sort((a, b) => (a.code < b.code ? -1 : a.code > b.code ? 1 : 0))) {
    const list = byCategory.get(e.category) ?? [];
    list.push(e);
    byCategory.set(e.category, list);
  }
  const badge = (/** @type {string} */ severity) =>
    severity === "warning"
      ? '<span class="diagnostic-severity">Warning</span> '
      : severity === "hint"
        ? '<span class="diagnostic-severity">Hint</span> '
        : "";
  let out = "---\ntitle: Diagnostic index\n---\n";
  out +=
    "<!-- GENERATED FILE — do not edit by hand, and not committed.\n" +
    "     Source: src/generated/diagnostics/*.json (scripts/build-diagnostics-index.mjs).\n" +
    "     Regenerated by `npm run build` and `npm run dev`. -->\n\n";
  out +=
    "Every diagnostic code the compiler can emit, with a one-line summary of the cause, grouped by category. " +
    "Each code links to its own page: what the code means, how to fix it and an example where an explanation is written, " +
    "the grammar rules it governs, and the Book pages that explain it. " +
    "`bynk explain <code>` prints a code's explanation in a terminal, and in VS Code the diagnostic's **Explain** quick fix " +
    "(or **Bynk: Explain Diagnostic Code…**) shows the same text in a panel, offline.\n\n";
  out += `There are **${entries.length}** codes in total. Every code is an error unless it is marked **Warning** or **Hint**.\n`;
  // The site's filter box (`site/public/diagnostic-filter.js`) adds itself here, above the
  // first category, and narrows the lists as you type.
  out += '\n<script type="module" src="/diagnostic-filter.js"></script>\n';
  for (const title of [...byCategory.keys()].sort()) {
    out += `\n## ${title}\n\n`;
    for (const e of byCategory.get(title) ?? []) {
      out += `- [\`${e.code}\`](${INDEX_PATH}${e.code}/) — ${badge(e.severity)}${e.summary}\n`;
    }
  }
  if (retired.length > 0) {
    out +=
      "\n## Retired codes\n\n" +
      "Codes the compiler no longer emits. `bynk explain <code>` still says when each was retired and why.\n\n";
    for (const r of [...retired].sort((a, b) => (a.code < b.code ? -1 : a.code > b.code ? 1 : 0))) {
      const by = r.replacement ? ` Replaced by ${r.replacement}.` : "";
      out += `- [\`${r.code}\`](${INDEX_PATH}${r.code}/) — retired after v${r.lastRelease}. ${r.why}${by}\n`;
    }
  }
  return out;
}

function main() {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, renderIndex(readEntries(DIR), readRetired(DIR)));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
